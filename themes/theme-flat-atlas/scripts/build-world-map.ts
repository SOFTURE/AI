// Writes src/map/world-110m.ts: the Natural Earth 1:110m countries (world-atlas) without Antarctica, projected with
// Natural Earth II into a 1000 x 500 viewBox, as SVG path data, plus a 10 degree graticule and the fit the runtime
// projection reuses for pins. Run after a world-atlas or projection change: `npm run map:build -w @softure-ai/theme-flat-atlas`.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

import { geoGraticule10, geoPath, geoProjection } from "d3-geo";
import type { FeatureCollection, Geometry } from "geojson";
import { feature } from "topojson-client";
import type { GeometryCollection, Topology } from "topojson-specification";

import { projectNaturalEarth2 } from "../src/map/projection.js";

const require = createRequire(import.meta.url);
const WIDTH = 1000;
const HEIGHT = 500;
const ANTARCTICA_ID = "010";
const OUTPUT = fileURLToPath(new URL("../src/map/world-110m.ts", import.meta.url));

type CountriesTopology = Topology<{ countries: GeometryCollection<{ name: string }> }>;

const topology = JSON.parse(readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8")) as CountriesTopology;
const countries = feature(topology, topology.objects.countries).features.filter((country) => country.id !== ANTARCTICA_ID);
const land: FeatureCollection<Geometry, { name: string }> = { type: "FeatureCollection", features: countries };

const projection = geoProjection(projectNaturalEarth2).fitExtent([[2, 2], [WIDTH - 2, HEIGHT - 2]], land).precision(0.2);
const path = geoPath(projection).digits(1);

const shapes = countries
  .map((country) => ({ id: country.id === undefined ? null : String(country.id), name: country.properties.name, d: path(country) ?? "" }))
  .filter((shape) => shape.d !== "")
  .sort((a, b) => a.name.localeCompare(b.name, "en"));
const [translateX, translateY] = projection.translate();
const fit = { scale: projection.scale(), translateX, translateY };

const lines = [
  "// Generated by scripts/build-world-map.ts from world-atlas/countries-110m.json (Natural Earth 1:110m, public domain).",
  "// Do not edit by hand: run `npm run map:build -w @softure-ai/theme-flat-atlas`.",
  'import type { MapFit } from "./projection.js";',
  "",
  "/** One country's shape: ISO 3166-1 numeric id (null for the few Natural Earth units without one), English name, SVG path. */",
  "export interface CountryShape {",
  "  readonly id: string | null;",
  "  readonly name: string;",
  "  readonly d: string;",
  "}",
  "",
  `export const WORLD_MAP_VIEWBOX = { width: ${WIDTH}, height: ${HEIGHT} } as const;`,
  "",
  `export const WORLD_MAP_FIT: MapFit = ${JSON.stringify(fit)};`,
  "",
  `export const WORLD_GRATICULE_PATH = ${JSON.stringify(path(geoGraticule10()) ?? "")};`,
  "",
  "export const WORLD_COUNTRY_SHAPES: readonly CountryShape[] = [",
  ...shapes.map((shape) => `  ${JSON.stringify(shape)},`),
  "];",
  "",
];
writeFileSync(OUTPUT, lines.join("\n"));
console.log(`world map: ${String(shapes.length)} countries written to ${OUTPUT}`);
